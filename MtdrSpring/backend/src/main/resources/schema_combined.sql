CREATE OR REPLACE TRIGGER EQUIPO63.TRG_TAREA_INICIO_REAL
BEFORE UPDATE OF ID_ESTADO ON EQUIPO63.TAREAS
FOR EACH ROW
BEGIN
    IF :NEW.ID_ESTADO = 2
       AND NVL(:OLD.ID_ESTADO, -1) <> 2
       AND :OLD.FECHA_INICIO_REAL IS NULL THEN
        :NEW.FECHA_INICIO_REAL := SYSTIMESTAMP;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER EQUIPO63.TRG_TAREA_FIN_REAL
BEFORE UPDATE OF ID_ESTADO ON EQUIPO63.TAREAS
FOR EACH ROW
DECLARE
    V_HORAS NUMBER(10,2);
BEGIN
    IF :NEW.ID_ESTADO = 4
       AND NVL(:OLD.ID_ESTADO, -1) <> 4 THEN
        :NEW.FECHA_FIN_REAL := SYSTIMESTAMP;
        IF :OLD.FECHA_INICIO_REAL IS NOT NULL THEN
            V_HORAS := ROUND(
                (CAST(:NEW.FECHA_FIN_REAL AS DATE)
                - CAST(:OLD.FECHA_INICIO_REAL AS DATE)) * 24,
                2
            );
            :NEW.HORAS_REALES := V_HORAS;
        END IF;
    END IF;
END;
/

